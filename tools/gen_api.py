#!/usr/bin/env python3
"""Generate the agent- and human-facing API index of OscInt.

Inputs (both committed):
  stamps/statements.json     generated by `make statements` (names, labels, proved_by, commitments, stamps)
  docs/api/annotations.json  hand-written, one entry per statement label: plain-word hypotheses and conclusion, rate,
                             uniformity, smoothness, see-also labels, and a Lean usage snippet
Outputs (both committed, regenerated by `make api`, checked by `make api-check`, which `make quick` runs):
  docs/api.json              the index (statements.json fields + annotations), for people and agents
  examples/api/Snippets.lean every snippet, compiled by `make quick` against `import OscInt.API`

Checks (exit 1 with a message naming the label): every statement has an annotation and vice versa; see-also labels
exist; a proved statement's snippet names its `proved_by` theorem; an unproved statement's snippet names its
statement constant and not a theorem; in --check mode, the committed outputs equal the regenerated ones byte for byte.
Usage: tools/gen_api.py [--check] [REPO]
"""
import json, os, sys

check = '--check' in sys.argv
args = [a for a in sys.argv[1:] if a != '--check']
repo = args[0] if args else '.'

def rd(p):
    with open(os.path.join(repo, p), encoding='utf-8') as f:
        return f.read()

st = json.loads(rd('stamps/statements.json'))
ann = json.loads(rd('docs/api/annotations.json'))
by_label = {s['label']: s for s in st['statements']}
errors = []
for lab in by_label:
    if lab not in ann['statements']:
        errors.append(f'{lab}: no annotation in docs/api/annotations.json')
for lab in ann['statements']:
    if lab not in by_label:
        errors.append(f'{lab}: annotation for a label that stamps/statements.json does not have')

def lean_text(path, const):
    """The frozen `def <const> : Prop := ...` block, verbatim, from the statement file."""
    lines = rd(path).split('\n')
    for i, l in enumerate(lines):
        if l.startswith('def ' + const + ' ') or l.startswith('def ' + const + ':'):
            j = i
            while j < len(lines) and lines[j].strip() != '':
                j += 1
            return '\n'.join(lines[i:j])
    errors.append(f'{const}: definition not found in {path}')
    return None


FIELDS = ['hypotheses', 'conclusion', 'rate', 'uniform_over', 'smoothness', 'see_also', 'snippet']
entries = []
snippets = []
for s in st['statements']:
    lab = s['label']
    a = ann['statements'].get(lab)
    if a is None:
        continue
    for f in FIELDS:
        if f not in a:
            errors.append(f'{lab}: annotation lacks field {f!r}')
    for o in a.get('see_also', []):
        if o not in by_label:
            errors.append(f'{lab}: see_also names unknown label {o!r}')
    snip = a.get('snippet', '')
    short = (s['proved_by'] or '').split('.')[-1]
    const = s['name'].split('.')[-1]
    if s['proved_by']:
        if short not in snip:
            errors.append(f'{lab}: snippet does not use its proving theorem {s["proved_by"]}')
    elif const not in snip:
        errors.append(f'{lab}: unproved statement; its snippet must use the constant {const} (as a hypothesis)')
    e = {k: s[k] for k in ['label', 'name', 'proved_by', 'summary', 'file', 'commitment', 'stamp']}
    e['lean_statement'] = lean_text(s['file'], const)
    e.update({f: a.get(f) for f in FIELDS if f != 'snippet'})
    e['snippet'] = snip
    e['status'] = 'see docs/STATUS.md (row ' + lab + ')'
    entries.append(e)
    snippets.append(f'/-! ### {lab}: {s["summary"]} -/\n\n{snip.rstrip()}\n')

if errors:
    print('api: FAIL\n  ' + '\n  '.join(errors))
    sys.exit(1)

out_json = json.dumps({
    'format': 'oscint-api/1',
    'generated_by': 'tools/gen_api.py from stamps/statements.json and docs/api/annotations.json',
    'entry_point': 'import OscInt.API',
    'conventions': ann['conventions'],
    'helpers': ann['helpers'],
    'lean_toolchain': st['lean_toolchain'],
    'mathlib_rev': st['mathlib_rev'],
    'statements': entries,
}, ensure_ascii=False, indent=1) + '\n'
out_lean = ('import OscInt.API\n\n/-! Usage snippets of every OscInt statement, generated by `tools/gen_api.py` from '
            '`docs/api/annotations.json`;\ncompiled by `make quick`. Do not edit: edit the annotations and run `make api`. -/\n\n'
            'open OscInt.Statements\n\nnamespace OscIntSnippets\n\n' + '\n'.join(snippets) + '\nend OscIntSnippets\n')

targets = {'docs/api.json': out_json, 'examples/api/Snippets.lean': out_lean}
if check:
    bad = []
    for p, txt in targets.items():
        try:
            cur = rd(p)
        except FileNotFoundError:
            cur = None
        if cur != txt:
            bad.append(p)
    if bad:
        print('api: FAIL: out of date (run `make api` and commit): ' + ', '.join(bad))
        sys.exit(1)
    print(f'api: ok: {len(entries)} statements annotated, outputs up to date')
else:
    os.makedirs(os.path.join(repo, 'examples/api'), exist_ok=True)
    for p, txt in targets.items():
        with open(os.path.join(repo, p), 'w', encoding='utf-8') as f:
            f.write(txt)
    print(f'api: wrote docs/api.json and examples/api/Snippets.lean ({len(entries)} statements)')
